# Mood -> frame. Several moods intentionally share a frame; there are only
# six distinct drawings and duplicating them would be dishonest.
MOOD_FRAMES = {
    "chill": FACE_NEUTRAL,
    "big-sis-energy": FACE_NEUTRAL,
    "hyped": FACE_SURPRISED,
    "chaotic": FACE_SURPRISED,
    "deep-thinker": FACE_THINKING,
    "sarcastic": FACE_SARCASTIC,
    "coding": FACE_CODING,
    "sleepy": FACE_SLEEPY,
}

# Moods a user can pass to /face or reach via Ctrl+F.
SELECTABLE_MOODS = tuple(MOOD_FRAMES)


def render_face(mood="chill", blink=False, speaking=False, phase=0, thinking=False):
    """
    Pick the frame for the current state.

    Priority: thinking > blink > speaking > mood.
    While speaking, alternate the mood frame with an open-mouth frame so
    the mouth visibly moves. If the mood frame already is the open-mouth
    one, fall back to neutral for the alternate so the swap stays visible.
    """
    if thinking:
        return FACE_THINKING

    if blink:
        return FACE_BLINK

    base = MOOD_FRAMES.get(mood, FACE_NEUTRAL)

    if speaking and phase % 2:
        return FACE_NEUTRAL if base is FACE_SURPRISED else FACE_SURPRISED

    return base


def face_dimensions(face=FACE_NEUTRAL):
    lines = face.strip("\n").splitlines()
    return max((len(line) for line in lines), default=0), len(lines)


FACE_WIDTH, FACE_HEIGHT = face_dimensions()
